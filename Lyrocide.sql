CREATE DATABASE IF NOT EXISTS lycoride;
USE lycoride;

CREATE TABLE IF NOT EXISTS Users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('STUDENT','RIDER') NOT NULL DEFAULT 'STUDENT',
  name VARCHAR(120),
  phone VARCHAR(30),
  city VARCHAR(80),
  address VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS drivers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  car VARCHAR(120) NOT NULL,
  rating DECIMAL(2,1) DEFAULT 5.0,
  eta_min INT DEFAULT 5,
  fare_mult DECIMAL(3,2) DEFAULT 1.00,
  active TINYINT(1) DEFAULT 1
);

CREATE TABLE IF NOT EXISTS trips (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  driver_id INT NOT NULL,
  destination VARCHAR(255) NOT NULL,
  dest_lat DOUBLE, dest_lng DOUBLE,
  km DECIMAL(5,1) NOT NULL,
  fare INT NOT NULL,
  rating TINYINT NULL,
  comment VARCHAR(500) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (driver_id) REFERENCES drivers(id)
);

CREATE TABLE  IF NOT EXISTS notifications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  title VARCHAR(120), body VARCHAR(300),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

